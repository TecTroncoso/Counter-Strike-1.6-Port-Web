#!/bin/sh
# Generate server-owned GoldSrc configuration from the deployment environment.
# No browser request can modify these values at runtime.
set -eu
umask 077

HLDS_ROOT="${HLDS_DIR:-/app}"
GAME_DIR="${HLDS_GAME_DIR:-${HLDS_ROOT}/cstrike}"
HLDS_MAP="${HLDS_MAP:-de_dust2}"
HLDS_BOT_QUOTA="${HLDS_BOT_QUOTA:-9}"
HLDS_MAXPLAYERS="${HLDS_MAXPLAYERS:-16}"

fail() {
  echo "cs16-entrypoint: $*" >&2
  exit 1
}

case "$HLDS_MAP" in
  ""|*[!A-Za-z0-9_-]*) fail "HLDS_MAP must contain only letters, digits, '_' or '-'" ;;
esac
case "$HLDS_BOT_QUOTA" in
  ""|*[!0-9]*) fail "HLDS_BOT_QUOTA must be an integer from 0 to 32" ;;
esac
[ "$HLDS_BOT_QUOTA" -le 32 ] || fail "HLDS_BOT_QUOTA must be an integer from 0 to 32"
case "$HLDS_MAXPLAYERS" in
  ""|*[!0-9]*) fail "HLDS_MAXPLAYERS must be an integer from 1 to 32" ;;
esac
[ "$HLDS_MAXPLAYERS" -ge 1 ] || fail "HLDS_MAXPLAYERS must be an integer from 1 to 32"
[ "$HLDS_MAXPLAYERS" -le 32 ] || fail "HLDS_MAXPLAYERS must be an integer from 1 to 32"
[ "$HLDS_BOT_QUOTA" -le "$HLDS_MAXPLAYERS" ] || fail "HLDS_BOT_QUOTA cannot exceed HLDS_MAXPLAYERS"

[ -d "$GAME_DIR" ] || fail "HLDS game directory does not exist: $GAME_DIR"
[ -x "$HLDS_ROOT/hlds_linux" ] || fail "HLDS executable does not exist: $HLDS_ROOT/hlds_linux"
[ -f "$GAME_DIR/addons/metamod/config.ini" ] || fail "MetaMod configuration is missing"
[ -f "$GAME_DIR/addons/metamod/plugins.ini" ] || fail "MetaMod plugin configuration is missing"
[ -x "$GAME_DIR/addons/metamod/dlls/metamod.so" ] || fail "MetaMod-P loader is missing"
[ -x "$GAME_DIR/addons/yapb/bin/yapb.so" ] || fail "YaPB plugin is missing"
[ -f "$GAME_DIR/dlls/cs.so" ] || fail "ReGameDLL is missing"
[ -f "$GAME_DIR/maps/${HLDS_MAP}.bsp" ] || fail "HLDS map does not exist: $GAME_DIR/maps/${HLDS_MAP}.bsp"

cat > "$GAME_DIR/server.cfg.tmp" <<EOF
// Generated by /app/bridge/entrypoint.sh. Do not edit in the running container.
hostname "CS 1.6 Web Port"
sv_contact ""

maxplayers "$HLDS_MAXPLAYERS"

mp_timelimit 25
mp_autokick 0
mp_autoteambalance 1
mp_flashlight 0
mp_footsteps 1
mp_friendlyfire 1
mp_hostagepenalty 4
mp_limitteams 2
mp_tkpunish 1
sv_maxspeed 320
pausable 0
sys_ticrate 1000
sv_cheats 0
mp_playerid 1
mp_freezetime "6"
mp_roundtime "5"
mp_startmoney "800"
mp_c4timer "45"
mp_spawnprotectiontime 5

sv_alltalk 1
sv_voiceenable 1
sv_voicequality 1

log "on"
sv_logbans "1"
sv_logecho "1"
sv_logfile "1"
sv_log_onefile "0"

sv_allowupload 1
sv_allowdownload 1
sv_maxrate 25000
sv_maxupdaterate 100
sv_minrate 0
sv_minupdaterate 4
cl_cmdrate 101
cl_updaterate 101
EOF

# Replace the immutable image configuration with a deterministic runtime copy.
# The RCON password is required in production. It is never returned by the
# public health endpoint and is removed from the bridge process environment.
if [ "${NODE_ENV:-production}" = "production" ] && [ -z "${HLDS_RCON_PASSWORD:-}" ]; then
  fail "HLDS_RCON_PASSWORD is required in production"
fi
if [ -n "${HLDS_RCON_PASSWORD:-}" ]; then
  case "$HLDS_RCON_PASSWORD" in
    *[!A-Za-z0-9._~+/=-]*) fail "HLDS_RCON_PASSWORD contains unsupported characters" ;;
  esac
  printf 'rcon_password "%s"\n' "$HLDS_RCON_PASSWORD" >> "$GAME_DIR/server.cfg.tmp"
fi
mv "$GAME_DIR/server.cfg.tmp" "$GAME_DIR/server.cfg"

# MetaMod executes this immediately after loading YaPB. YaPB's main config is
# also updated so the same quota survives subsequent map changes.
cat > "$GAME_DIR/addons/metamod/exec.cfg.tmp" <<EOF
// Generated by /app/bridge/entrypoint.sh.
yb_quota $HLDS_BOT_QUOTA
EOF
mv "$GAME_DIR/addons/metamod/exec.cfg.tmp" "$GAME_DIR/addons/metamod/exec.cfg"
sed -E 's/^yb_quota[[:space:]]+.*/yb_quota "'"$HLDS_BOT_QUOTA"'"/' \
  "$GAME_DIR/addons/yapb/conf/yapb.cfg" > "$GAME_DIR/addons/yapb/conf/yapb.cfg.tmp"
mv "$GAME_DIR/addons/yapb/conf/yapb.cfg.tmp" "$GAME_DIR/addons/yapb/conf/yapb.cfg"

# A one-map cycle keeps the configured map and the map reported by /health
# consistent across round rotations.
printf '%s\n' "$HLDS_MAP" > "$GAME_DIR/mapcycle.txt"

# The bridge never needs the RCON secret; remove it before exec.
unset HLDS_RCON_PASSWORD
exec bun /app/bridge/index.ts
